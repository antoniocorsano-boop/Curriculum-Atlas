"""Validate the actual isolated variation independently of browser driver."""
import argparse,hashlib,importlib.util,json,math
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
spec=importlib.util.spec_from_file_location("lab",ROOT/"scripts/atlas-world-lab-variation.py")
lab=importlib.util.module_from_spec(spec);spec.loader.exec_module(lab)
def need(x,msg):
    if not x:raise ValueError(msg)
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def read(p):return lab.awc.ev.strict_json(p.read_bytes())
def validate(p,archives,master,revision):
    c,expected=lab.make_lab_plan(archives)
    plan=read(p/"lab-plan.json");composition=read(p/"composition-plan.json")
    need(plan==expected and composition==c,"plan drift")
    bay=read(p/"bay.json");r=read(p/"bay-browser.json")
    need(bay["revision"]==r["revision"]==revision,"executed revision")
    need(bay["masterUnchanged"] and sha(master)==plan["masterSha256"]==r["masterSha256"],"master identity")
    need(r["status"]=="PASS_NAVIGABLE_BAY_PREVIEW" and r["result"]["status"]=="PASS_BAY_BINDING","producer result")
    need(not r["externalRequests"] and not r["pageErrors"],"external requests or errors")
    obs=c["steps"][-1]["facts"]
    need(r["result"]["triangles"]==bay["triangles"]==obs["triangles"]==19008 and r["result"]["objects"]==obs["objects"]==11,"geometry inventory")
    need(bay["materialPackageSha256"]==r["packageSha256"] and bay["sha256"]==r["baySha256"],"geometry/material identity")
    # Compare regenerated byte-level geometry with the producer receipt.
    import zipfile
    index=read(ROOT/lab.awc.ev.INDEX)
    a=index["archives"]["bay"]
    with zipfile.ZipFile(Path(archives)/(str(a["artifact"])+".zip")) as z:
        old=lab.awc.ev.strict_json(z.read("bay.json"))
    need(bay["sha256"]==old["sha256"] and bay["materialPackageSha256"]==old["materialPackageSha256"],"historical geometry/material drift")
    metrics=r["result"]["metrics"]
    need(metrics["stable"]==5961 and metrics["tested"]==1068 and metrics["badVisibility"]==metrics["badSamples"]==0,"binding regression")
    need(metrics["maxUV"]<=.0002 and metrics["maxDiffuse"]<=.003 and metrics["maxRoughness"]<=.006,"binding tolerance")
    need(r["result"]["actualBay"] and r["result"]["sourceRoughness"] and r["result"]["agxLive"],"renderer regression")
    v=r["awc"]
    need(v["labPlanSha256"]==plan["labPlanSha256"] and v["compositionPlanSha256"]==c["planSha256"],"executed plan identity")
    before,after,restored=(v[k] for k in ("before","after","restored"))
    need(before==restored,"state rollback")
    need(before["yaw"]==plan["before"] and math.isclose(after["yaw"],plan["after"],abs_tol=1e-12),"orbit mismatch")
    for k in ("pitch","zoom","width","height","projection"):need(before[k]==after[k],"protected state changed: "+k)
    need(before["width"]==640 and before["height"]==480,"viewport")
    need(len(before["camera"])==len(after["camera"])==16 and all(math.isfinite(x) for x in before["camera"]+after["camera"]),"camera matrix")
    need(before["camera"]!=after["camera"],"camera not changed")
    views=r["views"]
    need(set(views)=={"reference","rotated","restored","mobile"},"view inventory")
    for name,q in views.items():
        need(sha(p/(name+".png"))==q["sha256"],"image identity "+name)
        need(q["lit"]>q["width"]*q["height"]*.04,"empty view")
    need(views["reference"]["sha256"]==views["restored"]["sha256"]!=views["rotated"]["sha256"],"visual rollback")
    need((views["mobile"]["width"],views["mobile"]["height"])==(320,240),"mobile viewport")
    need(not any(plan["authority"].values()) and not plan["productionExecutionAuthorized"],"authority")
    need(not any(r["result"][k] for k in ("artisticApproval","physicalDeviceQualified","publishable")),"producer promotion")
    return {"schema":"atlas.awc.lab-variation-report/v1","status":"PASS_AWC_D_ISOLATED_ORBIT","revision":revision,
            "producerRevision":plan["producerRevision"],"masterSha256":plan["masterSha256"],"labPlanSha256":plan["labPlanSha256"],
            "compositionPlanSha256":c["planSha256"],"before":before["yaw"],"after":after["yaw"],"restored":restored["yaw"],
            "cameraMatrixChanged":True,"protectedStateUnchanged":True,"rollbackExact":True,"views":views,
            "triangles":bay["triangles"],"objects":r["result"]["objects"],"sourceGeometrySha256":bay["sha256"],
            "sourceMaterialPackageSha256":bay["materialPackageSha256"],"bindingMetrics":metrics,
            "masterUnchanged":True,"productionExecutionAuthorized":False,"nativeRuntimeBinding":False,
            "artisticApproval":False,"physicalDeviceQualified":False,"publishable":False}
def main():
    p=argparse.ArgumentParser()
    p.add_argument("--out",type=Path,required=True);p.add_argument("--archives",type=Path,required=True)
    p.add_argument("--master",type=Path,required=True);p.add_argument("--revision",required=True)
    a=p.parse_args();r=validate(a.out,a.archives,a.master,a.revision)
    raw=json.dumps(r,sort_keys=True,indent=2,allow_nan=False)+"\n"
    (a.out/"lab-variation-report.json").write_text(raw);print(raw,end="")
if __name__=="__main__":main()

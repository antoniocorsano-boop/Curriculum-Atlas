#!/usr/bin/env python3
"""ATLAS-ATRIUM-3D-SEED-03: import the real GLB mesh, make a .blend, render 3 draft cameras.

Blender 3.6+/4.x/5.x, invoked as:
 blender -b --factory-startup --python import_seed_to_blender.py -- \
   --glb ATLAS-ATRIUM-3D-SEED-03.glb \
   --blueprint ATLAS-ATRIUM-BLUEPRINT-01.json \
   --output ./blender-evidence --render

Required .blend is produced from the GLB generated by generate_atrium_seed.py.
THIS IS A SEED-03 ONLY, not a certified art-direction match or professional Cycles master.
"""
from __future__ import annotations
import argparse,hashlib,json,math,sys
from pathlib import Path
import bpy
from mathutils import Vector,Matrix


def args():
    params=sys.argv[sys.argv.index('--')+1:] if '--' in sys.argv else []
    p=argparse.ArgumentParser()
    p.add_argument('--glb',required=True)
    p.add_argument('--blueprint',required=True)
    p.add_argument('--output',required=True)
    p.add_argument('--render',action='store_true',help='Produce draft Cycles images for HERO SIDE MOBILE')
    p.add_argument('--samples',type=int,default=12)
    return p.parse_args(params)


def checksum(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def look_at(o,xyz):
    direction=Vector(xyz)-o.location
    o.rotation_euler=direction.to_track_quat('-Z','Y').to_euler()


def material(name,hexstr,roughness=.42,metallic=0.0,alpha=1.0,emission=0.0):
    m=bpy.data.materials.new(name)
    m.use_nodes=True
    rgb=tuple(int(hexstr[k:k+2],16)/255.0 for k in (0,2,4))
    m.diffuse_color=(*rgb,alpha)
    p=m.node_tree.nodes.get('Principled BSDF')
    if p is not None:
        p.inputs['Base Color'].default_value=(*rgb,1)
        p.inputs['Roughness'].default_value=roughness
        p.inputs['Metallic'].default_value=metallic
        if 'Alpha' in p.inputs:p.inputs['Alpha'].default_value=alpha
        if emission and 'Emission Color' in p.inputs:p.inputs['Emission Color'].default_value=(*rgb,1)
        if emission and 'Emission Strength' in p.inputs:p.inputs['Emission Strength'].default_value=emission
        if 'Transmission Weight' in p.inputs and alpha<1:p.inputs['Transmission Weight'].default_value=.45
        if 'Transmission' in p.inputs and alpha<1:p.inputs['Transmission'].default_value=.45
    if alpha<1:
        # Blender 4.2+ render method; older versions use blend_method.
        if hasattr(m,'surface_render_method'):m.surface_render_method='DITHERED'
        elif hasattr(m,'blend_method'):m.blend_method='BLEND'
    return m


def make_materials():
    return {
     'floor':material('Stone · Midnight Blue','152b40',.19,.24),
     'wall':material('Wall · Blue Graphite','101d31',.66,.26),
     'recess':material('Recess · Blue Black','07182a',.71,.1),
     'metal':material('Metal · Anodized Blue','31506b',.32,.78),
     'bronze':material('Metal · Champagne Gold','b89a67',.28,.82),
     'gold':material('LED · Warm Gold','e9bd73',.35,.25,emission=2.0),
     'glass':material('Glass · Cobalt Blue','275b98',.18,.05,alpha=.42),
     'balustrade':material('Glass · Architectural Blue','c8e6ef',.12,.04,alpha=.28),
     'books':material('Books · Warm Brown','715746',.76,.04),
     'leaf':material('Plants · Emerald','275f54',.72,.03),
     'dome':material('Podium · Metallic Navy','173458',.22,.65),
    }


def byname(name,mat):
    if name.startswith('ARCH_FLOOR_POLISHED_STONE'):return mat['floor']
    if name.startswith('PODIUM_LOW_'):return mat['dome']
    if name.startswith('GARDEN_'):
        if 'CANOPY' in name:return mat['leaf']
        if 'TRUNK' in name:return mat['books']
        return mat['bronze']
    if name.startswith('BOOK'):return mat['books']
    if 'GLAZING' in name:return mat['glass']
    if 'GLASS_BALUSTRADE' in name:return mat['balustrade']
    if any(s in name for s in ('WARM_LIGHT','CONCENTRIC_LED','BASE_LED','SKYLIGHT_WARM','LABEL_STRIP','ICON_STRIP')):return mat['gold']
    if any(s in name for s in ('BRONZE','STRUCTURE','CAP_','OUTER_BRONZE','ANNULAR_LED','PODIUM_PLATFORM','GARDEN_','SKYLIGHT_RIB')):
        return mat['bronze']
    if 'PAVING_JOINT' in name:return mat['metal']
    if name.startswith('COLUMN'):return mat['metal']
    if 'GALLERY' in name:return mat['metal']
    if 'WALL' in name or 'ROTUNDA' in name or 'ROOF' in name:return mat['wall']
    return mat['metal']


def create_text(name,label,loc,rot,size,mat,width_limit=None):
    curve=bpy.data.curves.new(name,'FONT')
    curve.body=label
    curve.align_x='CENTER';curve.align_y='CENTER'
    curve.size=size;curve.extrude=.0004
    obj=bpy.data.objects.new(name,curve)
    bpy.context.collection.objects.link(obj)
    obj.location=loc;obj.rotation_euler=rot
    obj.data.materials.append(mat)
    bpy.context.view_layer.update()
    if width_limit and obj.dimensions.x>width_limit:
        obj.scale*=width_limit/obj.dimensions.x
    return obj


def area(name,loc,target,power,color,size):
    data=bpy.data.lights.new(name,'AREA')
    data.energy=power;data.color=color;data.shape='DISK';data.size=size
    obj=bpy.data.objects.new(name,data);bpy.context.collection.objects.link(obj)
    obj.location=loc;look_at(obj,target)
    return obj


def camera(name,info):
    data=bpy.data.cameras.new(name)
    data.type='PERSP';data.sensor_fit='HORIZONTAL'
    data.angle=math.radians(info['horizontal_fov_deg'])
    obj=bpy.data.objects.new(name,data)
    bpy.context.collection.objects.link(obj)
    obj.location=info['position'];look_at(obj,info['target'])
    obj.data.clip_end=150
    return obj


def main():
    a=args();glb=Path(a.glb).resolve();blue=Path(a.blueprint).resolve();out=Path(a.output).resolve()
    out.mkdir(parents=True,exist_ok=True)
    if not glb.is_file() or not blue.is_file():raise FileNotFoundError('missing GLB or blueprint')
    config=json.loads(blue.read_text('utf8'))
    assert config['reference']['sha256']=='7b3ffb9a355b89057acea02489020ad43d871e10b6cf5bbb29f8769ff3073336'
    bpy.ops.object.select_all(action='SELECT');bpy.ops.object.delete(use_global=False)
    bpy.ops.import_scene.gltf(filepath=str(glb))
    meshes=[o for o in bpy.context.scene.objects if o.type=='MESH']
    assert len(meshes)>=100, 'GLB not imported as distinct 3D meshes'
    mats=make_materials()
    for o in meshes:
        mat=byname(o.name,mats)
        o.data.materials.clear();o.data.materials.append(mat)
    # Create real text geometry while retaining HTML as navigation authority.
    data=config['dimensions_R'];r=data['portal_radius']
    for q,deg in zip(config['portals'],data['portal_angles_from_rear_y_deg']):
        angle=math.radians(deg)
        x,y=r*math.sin(angle),r*math.cos(angle)
        normal=(math.sin(angle),math.cos(angle))
        z=data['portal_base_z']+data['portal_height']*.68
        rotation=(Matrix.Rotation(-angle,4,'Z')@Matrix.Rotation(math.pi/2,4,'X')).to_euler()
        create_text('PORTAL_LABEL_'+q['id'],q['name'].upper(),(x-normal[0]*.026,y-normal[1]*.026,z),rotation,.022,mats['gold'],width_limit=.139)
    create_text('ATLAS_PODIUM_BRAND','ATLAS',(0,-.179,.10),(math.pi/2,0,0),.044,mats['gold'],width_limit=.22)
    cams={name:camera(name,d) for name,d in config['cameras_R'].items()}
    scene=bpy.context.scene
    scene.camera=cams['CAM_HERO']
    scene.render.engine='CYCLES'
    scene.cycles.samples=a.samples
    if hasattr(scene.cycles,'use_denoising'):scene.cycles.use_denoising=True
    scene.render.image_settings.file_format='PNG'
    scene.render.film_transparent=False
    # Seed lighting; artist must replace with final physically validated lights.
    area('SKYLIGHT_AREA_LIGHT',(0,0,1.56),(0,0,.15),180,(.75,.86,1),.55)
    area('FOYER_WARM_KEY_LEFT',(-.81,-.38,.71),(0,.3,.24),75,(1,.74,.38),.65)
    area('FOYER_WARM_KEY_RIGHT',(.81,-.38,.71),(0,.3,.24),75,(1,.74,.38),.65)
    area('FRONT_FILL',(0,-1.3,.48),(0,.22,.4),45,(.70,.84,1),.72)
    # A blue world illuminates the unroofed skylight, not a substitute for geometry.
    world=bpy.data.worlds.new('ATLAS Night Azure World')
    world.use_nodes=True
    bg=world.node_tree.nodes.get('Background')
    bg.inputs['Color'].default_value=(.08,.18,.33,1)
    bg.inputs['Strength'].default_value=.6
    scene.world=world
    try:scene.view_settings.view_transform='AgX'
    except Exception:pass
    try:scene.view_settings.look='Medium High Contrast'
    except Exception:pass
    output_blend=out/'atlas-atrium-3d-seed-03.blend'
    bpy.ops.wm.save_as_mainfile(filepath=str(output_blend),check_existing=False)
    render_paths={}
    if a.render:
        for name in ('CAM_HERO','CAM_SIDE','CAM_MOBILE'):
            scene.camera=cams[name]
            ratio=config['cameras_R'][name]['ratio']
            if ratio[0]>ratio[1]:scene.render.resolution_x,scene.render.resolution_y=800,450
            else:scene.render.resolution_x,scene.render.resolution_y=450,800
            scene.render.resolution_percentage=100
            scene.render.filepath=str(out/(name.lower()+'.png'))
            bpy.ops.render.render(write_still=True)
            render_paths[name]=scene.render.filepath
    report={'schema':'atlas.atrium.blender-seed-evidence/v3',
        'status':'BLENDER_DRAFT_RENDERED' if a.render else 'BLENDER_MASTER_DRAFT_SAVED',
        'glb_sha256':checksum(glb),'blueprint_sha256':checksum(blue),
        'blend_sha256':checksum(output_blend),
        'blend_size_bytes':output_blend.stat().st_size,
        'mesh_nodes_imported':len(meshes),
        'camera_names':sorted(cams.keys()),'render_paths':render_paths,
        'production_quality':'NOT_APPROVED_ART_DIR_02_REFERENCE_NOT_FITTED',
        'samples':a.samples}
    (out/'atlas-atrium-blender-evidence.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(report,indent=2))

if __name__=='__main__':main()

import {readFileSync} from "node:fs";
import {resolve,dirname} from "node:path";
import {fileURLToPath} from "node:url";
import {createHash} from "node:crypto";
const root=dirname(fileURLToPath(import.meta.url));
const pkg=resolve(root,"gateway-package");
const receipt=JSON.parse(readFileSync(resolve(pkg,"native-build-receipt.json"),"utf8"));
const sha=p=>createHash("sha256").update(readFileSync(p)).digest("hex");
const scene=resolve(pkg,"scene.html"),manifest=resolve(pkg,"native-manifest.json");
if(receipt.profile!=="M2-micro-integrated"||receipt.materialDetailApplied!==true||sha(scene)!==receipt.sceneSha256||sha(manifest)!==receipt.manifestSha256)throw Error("Pacchetto Atlas non integro");
process.env.ATLAS_GATEWAY_PREVIEW="true";
process.env.ATLAS_GATEWAY_NATIVE_PREVIEW="true";
process.env.ATLAS_LIBRARY_WEB_DELIVERY="true";
process.env.ATLAS_GATEWAY_SCENE_FILE=scene;
process.env.ATLAS_GATEWAY_SCENE_SHA256=receipt.sceneSha256;
process.env.ATLAS_GATEWAY_NATIVE_MANIFEST=manifest;
process.env.ATLAS_GATEWAY_NATIVE_MANIFEST_SHA256=receipt.manifestSha256;
process.env.HOSTNAME="127.0.0.1";
process.env.PORT=process.env.PORT||"3000";
delete process.env.ATLAS_GITHUB_PAGES;
delete process.env.ATLAS_PREVIEW_ROOT_SCOPED;
process.chdir(root);
console.log("Biblioteca Atlas: http://127.0.0.1:"+process.env.PORT+"/gateway/");
await import("./server.js");

import assert from 'node:assert/strict';
import {invalidatedGates,evidenceRemainsEligible} from './percorsi-g2-invalidation.mjs';
const has=(change,gates)=>{const r=invalidatedGates([change]); assert.equal(r.status,'PASS'); for(const g of gates) assert.equal(r.gates.includes(g),true,`${change} must invalidate ${g}`);};
assert.deepEqual(invalidatedGates([]),{status:'PASS',gates:[]});
for(const change of ['runtimeExactHead','pathwayId','contentVersion','publicationId']) has(change,['Q1','Q2','Q3','Q4','Q5','Q6','Q7','Q8']);
has('route',['Q1','Q4','Q7','Q8']);
has('storageOfflineNetwork',['Q2','Q3','Q7','Q8']);
has('uiInteraction',['Q4','Q7']);
has('authorityPublicationMetadata',['Q5','Q6','Q8','Q9']);
has('buildIndex',['Q1','Q6']);
has('producerPolicy',['Q1','Q5','Q6']);
assert.equal(evidenceRemainsEligible('Q5',['route']).eligible,true);
assert.equal(evidenceRemainsEligible('Q1',['route']).eligible,false);
assert.equal(evidenceRemainsEligible('Q6',['buildIndex']).eligible,false);
assert.equal(invalidatedGates(['unknownDomain']).status,'BLOCKED');
console.log('PASS governed full invalidation/revalidation table and fail-closed unknown change');
